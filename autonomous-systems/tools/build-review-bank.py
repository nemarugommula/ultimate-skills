"""Build assets/review-bank.js from every lesson quiz, for review.html (Autonomous Systems; forked from the AI Engineer course).

Run after adding, editing or reordering quizzes:   python3 tools/build-review-bank.py
Lessons stay the single source of truth; the bank is a generated copy (works from file://).
Quiz ids match the lesson pages' saved answers: "<lessonId>#<position on the page>".
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LESSON_RE = re.compile(r'\{ id: "([^"]+)", title: "((?:[^"\\]|\\.)*)", href: "([^"]+)"')


def lessons():
    src = open(os.path.join(ROOT, "assets", "course.js"), encoding="utf-8").read()
    manifest = src[src.index("const COURSE = ["):src.index("\n];\n")]
    return LESSON_RE.findall(manifest)


def block(html, start, tag="div"):
    """Inner HTML of the element whose opening tag starts at `start` (matching nested tags)."""
    open_end = html.index(">", start) + 1
    depth, i = 1, open_end
    pat = re.compile(r"<(/?)%s\b[^>]*>" % tag)
    while depth:
        m = pat.search(html, i)
        if not m:
            raise ValueError("unclosed <%s> at %d" % (tag, start))
        depth += -1 if m.group(1) else 1
        i = m.end()
    return html[open_end:m.start()]


def rebase(fragment, page_dir):
    """Make relative links in a lesson fragment work from the course root."""
    def fix(m):
        attr, url = m.group(1), m.group(2)
        if re.match(r"^([a-z]+:|#|/)", url):
            return m.group(0)
        return '%s="%s"' % (attr, os.path.normpath(os.path.join(page_dir, url)).replace(os.sep, "/"))
    return re.sub(r'(href|src)="([^"]*)"', fix, fragment)


def clean(fragment, page_dir):
    return rebase(re.sub(r"\s+", " ", fragment).strip(), page_dir)


def quizzes(lesson_id, href):
    html = open(os.path.join(ROOT, href), encoding="utf-8").read()
    page_dir = os.path.dirname(href)
    out = []
    for qi, m in enumerate(re.finditer(r'<div class="quiz">', html)):
        q = block(html, m.start())
        qtext = re.search(r'<div class="qtext">', q)
        explain = re.search(r'<div class="explain">', q)
        opts = re.findall(r'<button class="opt"( data-ok)?>(.*?)</button>', q, re.S)
        oks = [i for i, (ok, _) in enumerate(opts) if ok]
        if not (qtext and explain and len(oks) == 1 and len(opts) >= 2):
            raise ValueError("%s quiz %d: needs .qtext, .explain, >=2 options and exactly one data-ok" % (href, qi))
        out.append({
            "id": "%s#%d" % (lesson_id, qi),
            "l": lesson_id,
            "q": re.sub(r"^\d+\.\s+", "", clean(block(q, qtext.start()), page_dir)),
            "o": [clean(t, page_dir) for _, t in opts],
            "k": oks[0],
            "e": clean(block(q, explain.start()), page_dir),
        })
    return out


def main():
    bank = []
    for lesson_id, _title, href in lessons():
        if os.path.exists(os.path.join(ROOT, href)):  # skip lessons not written yet
            bank.extend(quizzes(lesson_id, href))
    js = ("/* Generated by tools/build-review-bank.py from the lesson quizzes. Do not edit by hand. */\n"
          "window.REVIEW_BANK = " + json.dumps(bank, ensure_ascii=False, indent=0) + ";\n")
    with open(os.path.join(ROOT, "assets", "review-bank.js"), "w", encoding="utf-8") as f:
        f.write(js)
    print("wrote assets/review-bank.js: %d questions from %d lessons" % (len(bank), len({b["l"] for b in bank})))


if __name__ == "__main__":
    sys.exit(main())
